// Writes TypeScript types to src/api/schema.ts from the FastAPI app's OpenAPI document.
//
// By default the document is built from **this checkout's Python**, not fetched over
// HTTP. The old default was `http://127.0.0.1:8000`, which on the owner's machine is the
// running container: regenerating from a branch that added an endpoint read the deployed
// build instead and silently deleted the types the branch had just added. There is no
// port to get wrong if there is no port.
//
// Set GA_OPENAPI_URL to read a running server instead — for checking what a deployed
// build actually serves. It is never the default, and it says what it did.
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const repoRoot = new URL("../../", import.meta.url);
const outFile = new URL("../src/api/schema.ts", import.meta.url);

/** The checkout's interpreter, so the types come from these sources and these deps. */
function interpreter() {
  if (process.env.GA_PYTHON) return process.env.GA_PYTHON;
  const venv = fileURLToPath(new URL(".venv/bin/python", repoRoot));
  if (existsSync(venv)) return venv;
  return "python3";
}

function fromCheckout() {
  const python = interpreter();
  const result = spawnSync(python, ["-m", "odeda.api.openapi"], {
    cwd: fileURLToPath(repoRoot),
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) {
    throw new Error(`could not run ${python}: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(
      `${python} -m odeda.api.openapi exited ${result.status}\n${result.stderr}`,
    );
  }
  // A fixed label, not the interpreter path: the header is committed, and an absolute
  // path would rewrite the first line on every machine that regenerated it.
  return {
    schema: JSON.parse(result.stdout),
    from: "this checkout (python -m odeda.api.openapi)",
  };
}

async function fromUrl(apiUrl) {
  const url = new URL("/openapi.json", apiUrl);
  console.warn(
    `! reading a running server at ${url}\n` +
      "! the types will describe whatever that process is running, not this checkout",
  );
  return { schema: url, from: String(url) };
}

const { schema, from } = process.env.GA_OPENAPI_URL
  ? await fromUrl(process.env.GA_OPENAPI_URL)
  : fromCheckout();

const ast = await openapiTS(schema);
const header = `// Generated by \`npm run gen:api\` from ${from}. Do not edit.\n\n`;
await writeFile(outFile, header + astToString(ast));
console.log(`wrote src/api/schema.ts from ${from}`);
