// Pulls the FastAPI OpenAPI schema and writes TypeScript types to src/api/schema.ts.
// The backend must be running at VITE_API_URL (default http://127.0.0.1:8000), started
// without APP_PASSWORD, because /openapi.json sits behind the session gate otherwise.
import { writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const apiUrl = process.env.VITE_API_URL ?? "http://127.0.0.1:8000";
const schemaUrl = new URL("/openapi.json", apiUrl);

const ast = await openapiTS(schemaUrl);
const header = "// Generated by `npm run gen:api` from " + schemaUrl + ". Do not edit.\n\n";
await writeFile(new URL("../src/api/schema.ts", import.meta.url), header + astToString(ast));
console.log("wrote src/api/schema.ts from " + schemaUrl);
