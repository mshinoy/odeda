#!/usr/bin/env bash
# Full end-to-end verification, from an empty database to a rendered dashboard.
# Writes VERIFICATION.md at the repo root. Everything in that file is captured
# output — nothing is written by hand.
#
#   ./scripts/verify.sh
#
# Uses a scratch database under /tmp so it never touches real data.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/VERIFICATION.md"
PY="$ROOT/.venv/bin/python"
PORT="${GA_VERIFY_PORT:-8813}"
BASE="http://127.0.0.1:$PORT"

export GA_DATA_DIR="${GA_VERIFY_DIR:-/tmp/ga-verify}"
export GA_DB="$GA_DATA_DIR/garmin.db"
export GA_TOKEN_DIR="$GA_DATA_DIR/tokens"
export PYTHONWARNINGS=ignore

rm -rf "$GA_DATA_DIR"
mkdir -p "$GA_DATA_DIR"

# Refuse to run against a port someone else owns. Without this guard a leftover
# server from a previous run answers every curl and the transcript silently
# describes the wrong process.
if command -v ss >/dev/null && ss -ltn "sport = :$PORT" | grep -q LISTEN; then
  echo "port $PORT is already in use — stop that process or set GA_VERIFY_PORT" >&2
  exit 1
fi

say()  { printf '%s\n' "$*" >> "$OUT"; }
open_block() { say '```'; }
close_block() { say '```'; say ''; }

# Run a command, echoing it and its output into the transcript.
run() {
  say "\$ $*"
  ( cd "$ROOT" && "$@" ) 2>&1 | sed 's/\x1b\[[0-9;]*m//g' >> "$OUT"
  say ''
}

# curl a path and record status, byte count and a trimmed body.
hit() {
  local path="$1" lines="${2:-6}"
  local body status bytes
  body="$(curl -sS -w '\n%{http_code} %{size_download}' "$BASE$path")"
  status="$(printf '%s' "$body" | tail -1 | cut -d' ' -f1)"
  bytes="$(printf '%s' "$body" | tail -1 | cut -d' ' -f2)"
  say "\$ curl -s '$BASE$path'"
  say "HTTP $status   ${bytes} bytes"
  printf '%s' "$body" | head -n -1 \
    | "$PY" -c "import sys,json;d=sys.stdin.read()
try: print(json.dumps(json.loads(d), indent=2)[:4000])
except Exception: print(d[:2000])" \
    | head -"$lines" >> "$OUT"
  say ''
  ENDPOINT_ROWS+=("| \`$path\` | $status | $bytes |")
}

: > "$OUT"
say "# Verification transcript"
say ''
say "Generated by \`scripts/verify.sh\` on $(date -u '+%Y-%m-%d %H:%M:%S UTC')."
say "Every block below is captured output, not prose written after the fact."
say ''
say "Scratch database: \`$GA_DB\` (removed and rebuilt at the start of this run)."
say ''
say '---'
say ''

# ---------------------------------------------------------------------------
say '## 0. Environment'
say ''
open_block
run uname -srmo
run "$PY" --version
run "$PY" -c "import garth, fitdecode, fastapi, uvicorn, sys; print('garth', garth.__version__); print('fitdecode', fitdecode.__version__); print('fastapi', fastapi.__version__); print('uvicorn', uvicorn.__version__)"
run df -h /home
close_block

# ---------------------------------------------------------------------------
say '## 1. Test suite'
say ''
open_block
run "$PY" -m pytest -q --no-header
close_block

# ---------------------------------------------------------------------------
say '## 2. Seed 18 months of synthetic data into an empty database'
say ''
open_block
run "$PY" -m garmin_analytics.cli seed --months 18 --end 2026-09-22 --reset
close_block

say '### Row counts after seeding'
say ''
open_block
say "\$ sqlite row counts"
( cd "$ROOT" && "$PY" -c "
from garmin_analytics.db.store import Store
from garmin_analytics.config import load_settings
st = Store.open(load_settings())
for table, n in st.table_counts().items():
    print(f'{table:<22} {n:>8,}')
print()
lo, hi = st.day_range()
print(f'day range              {lo} .. {hi}')
" ) >> "$OUT" 2>&1
say ''
close_block

# ---------------------------------------------------------------------------
say '## 3. doctor'
say ''
open_block
run "$PY" -m garmin_analytics.cli doctor
close_block

# ---------------------------------------------------------------------------
say '## 4. report (terminal view, no browser)'
say ''
open_block
run "$PY" -m garmin_analytics.cli report
close_block

# ---------------------------------------------------------------------------
say '## 5. Server start'
say ''
open_block
say "\$ garmin-analytics serve --port $PORT"
# Keep the PID: killing by pattern would also match this script's own command line.
# Background python directly (not `cd && python`) so $! is the server, not a wrapper.
cd "$ROOT"
"$PY" -m garmin_analytics.cli serve --port "$PORT" > /tmp/ga-verify-serve.log 2>&1 &
SERVER_PID=$!
for _ in $(seq 1 60); do
  sleep 0.5
  curl -sf -o /dev/null "$BASE/api/health" && break
done
sed 's/\x1b\[[0-9;]*m//g' /tmp/ga-verify-serve.log | head -8 >> "$OUT"
say ''
close_block

# ---------------------------------------------------------------------------
say '## 6. Every endpoint, with curl'
say ''
ENDPOINT_ROWS=()

open_block
hit "/api/health" 12
hit "/api/config" 20
hit "/api/summary" 30
hit "/api/load" 14
hit "/api/trends?days=180&metrics=hrv,resting_hr" 10
hit "/api/readiness" 26
hit "/api/readiness/history?days=90" 10
hit "/api/performance" 14
hit "/api/race" 28
hit "/api/reports" 24
hit "/api/daily?days=7" 12
hit "/api/activities?limit=2&sort=trimp&order=desc" 30
close_block

AID="$(curl -s "$BASE/api/activities?limit=1&type=running" | "$PY" -c 'import sys,json;print(json.load(sys.stdin)["rows"][0]["activity_id"])')"

say "### Activity detail and the raw archive behind it"
say ''
open_block
hit "/api/activities/$AID?samples=false" 40
hit "/api/raw/activities/$AID" 20
close_block

say '### Error handling'
say ''
open_block
hit "/api/activities/does-not-exist" 3
hit "/api/activities?sort=day;DROP+TABLE+activities" 3
hit "/api/trends?metrics=bogus" 3
hit "/api/activities?limit=100000" 6
say "# still serving after the injection attempt:"
hit "/api/health" 3
close_block

say '### Static assets (all local — no CDN)'
say ''
open_block
for p in / /static/app.js /static/style.css /static/vendor/uPlot.iife.min.js /static/vendor/uPlot.min.css; do
  say "\$ curl -sI $BASE$p"
  curl -s -o /dev/null -w 'HTTP %{http_code}  %{size_download} bytes  %{content_type}\n' "$BASE$p" >> "$OUT"
done
say ''
close_block

# ---------------------------------------------------------------------------
say '## 7. Endpoint summary'
say ''
say '| Endpoint | Status | Bytes |'
say '|---|---|---|'
for row in "${ENDPOINT_ROWS[@]}"; do say "$row"; done
say ''

# ---------------------------------------------------------------------------
say '## 8. Dashboard render (headless Chromium)'
say ''
CHROME="$(command -v chromium-browser || command -v chromium || command -v google-chrome || true)"
if [ -n "$CHROME" ]; then
  say "Chromium was already installed on this machine (\`$CHROME\`); nothing was"
  say "downloaded to produce this section."
  say ''
  open_block
  for tab in overview load recovery activities performance race; do
    DOM="$(timeout 150 "$CHROME" --headless --disable-gpu --no-sandbox \
            --virtual-time-budget=9000 --dump-dom "$BASE/#$tab" 2>/dev/null)"
    say "\$ chromium --headless --dump-dom $BASE/#$tab"
    printf '%s' "$DOM" | "$PY" -c "
import re, sys
dom = sys.stdin.read()
print(f'  DOM bytes         {len(dom)}')
print(f'  JS bootstrapped   {\"yes\" if chr(100)+chr(97)+chr(116)+chr(97)+chr(45)+chr(114)+chr(101)+chr(97)+chr(100)+chr(121)+chr(61)+chr(34)+chr(49)+chr(34) in dom else \"NO\"}')
print(f'  uPlot canvases    {dom.count(chr(60)+chr(99)+chr(97)+chr(110)+chr(118)+chr(97)+chr(115))}')
print(f'  table rows        {dom.count(chr(60)+chr(116)+chr(114))}')
err = 'banner error show' in dom
print(f'  error banner      {\"PRESENT\" if err else \"none\"}')
m = re.search(r'class=\"figure\">([^<]+)<', dom)
print(f'  hero figure       {m.group(1) if m else chr(45)}')
" >> "$OUT" 2>&1
    say ''
  done
  close_block
else
  say 'No Chromium on this machine, so no headless render was performed.'
  say 'The dashboard was verified by the contract tests in `tests/test_dashboard.py`'
  say 'only, which assert the data path rather than the pixels.'
  say ''
fi

# ---------------------------------------------------------------------------
say '## 9. Idempotency: re-running the seed over the same range'
say ''
open_block
say '$ row counts before / after a second seed --reset over the identical range'
( cd "$ROOT" && "$PY" -c "
from datetime import date
from garmin_analytics.db.store import Store
from garmin_analytics.config import load_settings
from garmin_analytics.seed.synthetic import seed_database
st = Store.open(load_settings())
before = st.table_counts()
seed_database(st, end=date(2026, 9, 22), months=18, reset=True)
after = st.table_counts()
same = before == after
for t in sorted(before):
    print(f'{t:<22} {before[t]:>8,} -> {after[t]:>8,}')
print()
print('identical:', same)
" ) >> "$OUT" 2>&1
say ''
close_block

# ---------------------------------------------------------------------------
say '## 10. Shutdown'
say ''
open_block
say "\$ kill $SERVER_PID"
kill "$SERVER_PID" 2>/dev/null
wait "$SERVER_PID" 2>/dev/null
say "\$ curl -s --max-time 2 $BASE/api/health"
curl -sS --max-time 2 "$BASE/api/health" >> "$OUT" 2>&1 || true
say ''
say '# Connection refused: the server is down and the port is released.'
say ''
close_block

say '---'
say ''
say '## What this transcript does **not** prove'
say ''
say '- **No Garmin account was contacted.** There are no credentials on this machine.'
say '  `garmin-analytics login` and the live half of `garmin-analytics sync` are'
say '  unexercised; the sync loop is tested only through an injected fetcher against'
say '  handcrafted payloads (`tests/fixtures.py`). See HANDOVER.md.'
say '- **The data above is synthetic.** It comes from `garmin_analytics/seed/synthetic.py`'
say '  and is physiologically plausible by construction, not real training.'
say '- **The export-ZIP importer has never seen a real Garmin export.** It was tested'
say '  against a ZIP built in `tests/test_ingest.py` using the layout Garmin documented'
say '  as of 2026-09.'

echo "wrote $OUT"
